test('quiz shows both feedback states, resumes after reload, scores all 12 and retries', async ({ page }) => {
  await page.goto(base + '#hardware/quiz')
  const options = page.locator('.hw-option')
  await options.nth(0).click()
  await expect(page.getByText('Бұл жауап сәйкес келмейді')).toBeVisible()
  await expect(options.nth(1)).toHaveAttribute('data-result', 'correct')
  await page.reload()
  await expect(page.getByText('СҰРАҚ 2 / 12')).toBeVisible()
  await button(page, 'Алдыңғы сұрақ').click()
  await expect(options.nth(0)).toHaveAttribute('data-result', 'wrong')
  await button(page, 'Келесі сұрақ').click()
  const answers = [3, 0, 2, 1, 3, 0, 2, 1, 3, 0, 2]
  for (const [index, answer] of answers.entries()) {
    await options.nth(answer).click()
    await expect(page.locator('.hw-question .hw-feedback')).toContainText('Дұрыс жауап')
    if (index < answers.length - 1) await button(page, 'Келесі сұрақ').click()
  }
  await expect(page.getByText('11 / 12', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('11 / 12', { exact: true })).toBeVisible()
  await button(page, 'Қайта тапсыру').click()
  await expect(page.getByText('0/12 жауап берілді')).toBeVisible()
  await expect(options.nth(0)).toBeEnabled()
  await page.reload()
  await expect(page.getByText('СҰРАҚ 1 / 12')).toBeVisible()
})

test('troubleshooting supports multiple causes, explanation, all scenarios, persistence and retry', async ({ page }) => {
  await page.goto(base + '#hardware/troubleshooting')
  const checks = page.getByRole('checkbox')
  await checks.nth(0).check()
  await checks.nth(3).check()
  await button(page, 'Болжамды тексеру').click()
  await expect(page.getByText('Ескерілмеген ықтимал себеп.', { exact: true })).toHaveCount(2)
  await expect(page.getByText('Бұл жағдайға сәйкес емес.', { exact: true })).toBeVisible()
  await expect(page.getByText('Келесі тексеріс.', { exact: true })).toBeVisible()
  const answers = [[0, 2, 3], [1, 2, 3], [0, 2, 3], [0, 1, 3]]
  for (const [index, selected] of answers.entries()) {
    await page.locator('.hw-scenarios button').nth(index + 1).click()
    for (const item of selected) await checks.nth(item).check()
    await button(page, 'Болжамды тексеру').click()
    await expect(page.getByText('Берілген жағдайдағы ықтимал себептерді дұрыс таңдадың')).toBeVisible()
  }
  await expect(page.getByText('5/5 талданды')).toBeVisible()
  await page.reload()
  await expect(page.getByText('5/5 талданды')).toBeVisible()
  await button(page, 'Жағдайды қайта талдау').click()
  await expect(page.getByText('4/5 талданды')).toBeVisible()
})

test('teacher resources and mobile navigation render without page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto(base + '#hardware/teacher')
  await expect(page.getByRole('heading', { name: 'Teacher Mode' })).toBeVisible()
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(4)
  const lessons = page.locator('.hw-plan summary')
  await expect(lessons).toHaveCount(2)
  await lessons.first().focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('.hw-plan[open] li')).toHaveCount(5)
  for (const width of [360, 280]) {
    await page.setViewportSize({ width, height: 800 })
    for (const route of ['teacher', 'explorer', 'wiring', 'quiz', 'troubleshooting']) {
      const hash = '#hardware/' + route
      await page.goto(base + hash)
      await expect(page.locator('.hw-tabs [aria-current="page"]')).toHaveAttribute('href', hash)
      const scrollWidth = await page.evaluate(() => document.documentElement.scrollWidth)
      expect(scrollWidth, route + ' at ' + width + 'px').toBeLessThanOrEqual(width)
    }
  }
  await page.getByRole('button', { name: 'Мәзірді ашу' }).click()
  await expect(page.getByRole('navigation', { name: 'Бүйірлік мәзір' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Мәзірді ашу' })).toBeFocused()
})
