import { expect, test } from '@playwright/test'

const base = 'http://127.0.0.1:4173/'
const button = (page, name, exact = true) => page.getByRole('button', { name, exact })

test('homepage, existing anchors, keyboard explorer, all component content and persistence', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(base + '#hardware')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('FTC робототехникасын қазақша үйрен')
  await expect(page.locator('#hardware')).toBeVisible()
  await expect(page.locator('#programming')).toBeVisible()
  await expect(page.locator('#simulator')).toContainText('Жоспарда')
  await page.getByRole('link', { name: 'FTC Hardware', exact: true }).click()
  await expect(page).toHaveURL(/#hardware\/explorer$/)
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused()
  const cards = page.locator('.hw-component')
  await expect(cards).toHaveCount(12)
  const detail = page.locator('#hw-component-detail')
  for (let index = 0; index < 12; index++) {
    const card = cards.nth(index)
    const name = await card.locator('strong').textContent()
    await card.focus()
    await page.keyboard.press('Enter')
    await expect(card).toHaveAttribute('aria-expanded', 'true')
    await expect(detail.getByRole('heading', { name: new RegExp(name) })).toBeVisible()
    await expect(detail.locator('dt')).toHaveCount(3)
    await expect(detail.getByText('Жиі кездесетін қателер')).toBeVisible()
    await expect(card.locator('svg')).toBeVisible()
  }
  await expect(page.getByText('12/12 қаралды')).toBeVisible()
  await page.reload()
  await expect(page.getByText('12/12 қаралды')).toBeVisible()
  await page.getByRole('link', { name: 'Оқу бағыттарына қайту', exact: false }).click()
  await expect(page).toHaveURL(/#hardware$/)
  await expect(page.locator('#hardware')).toBeFocused()
  expect(errors).toEqual([])
})

